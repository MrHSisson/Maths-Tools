// Run against npm run dev. All sharing requests are intercepted: this does not edit shared decks.
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { chromium, expect } = require(process.env.PLAYWRIGHT_PATH ?? "playwright/test");
const base = process.env.SMOKE_URL ?? "http://127.0.0.1:5173";
const artifacts = process.env.SOLUTION_SMOKE_DIR ?? fs.mkdtempSync("/tmp/solution-smoke-");
fs.mkdirSync(artifacts, { recursive: true });
const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ["--no-sandbox"] });
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.route("**/api/decks*", (r) => r.fulfill({ status: 503, contentType: "application/json", body: '{"error":"Local browser test"}' }));
  const visit = async (slide) => {
    await page.goto(`${base}/decks/estimation?s=${slide}`);
    await page.getByRole("button", { name: "Show working", exact: true }).waitFor();
  };
  const root = () => page.locator(".solution-stepper");
  const stepCount = () => page.locator("[data-explanation]").count();
  await visit(9);
  const question = page.getByRole("region", { name: "Question", exact: true });
  await question.evaluate((el) => { el.dataset.identity = "same-question"; });
  const initial = await question.boundingBox();
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  await expect(root()).toHaveAttribute("data-solution-open", "true");
  await page.waitForTimeout(700);
  const working = page.getByRole("region", { name: "Worked solution", exact: true });
  const left = await working.boundingBox(), right = await question.boundingBox();
  expect(left.x + left.width).toBeLessThan(right.x);
  expect(right.x).toBeGreaterThan(initial.x + initial.width * 0.4);
  await expect(question).toHaveAttribute("data-identity", "same-question");
  expect(await stepCount()).toBe(1);
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.screenshot({ path: `${artifacts}/first-step.png` });
  await page.getByRole("button", { name: "Next step", exact: true }).click();
  expect(await stepCount()).toBe(2);
  await expect(page.locator('[data-step="1"]')).toHaveAttribute("data-past", "true");
  await expect(page.locator('[data-step="2"]')).toHaveAttribute("data-current", "true");
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.getByRole("button", { name: "Next step", exact: true }).click();
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.getByRole("button", { name: "Next step", exact: true }).click();
  await expect(page.locator(".solution-answer .solution-marker")).toHaveText("A");
  await expect(page.getByRole("button", { name: "Next step", exact: true })).toBeDisabled();
  await page.screenshot({ path: `${artifacts}/answer.png` });
  await page.getByRole("button", { name: "Previous step", exact: true }).click();
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.getByText("Solution options ···", { exact: true }).click();
  await page.getByRole("button", { name: "Step 1", exact: true }).click();
  expect(await stepCount()).toBe(1);
  await page.getByRole("button", { name: "Show all", exact: true }).click();
  await expect(root()).toHaveAttribute("data-solution-all", "true");
  expect(await stepCount()).toBe(3);
  await expect(page.locator("[data-answer]")).toHaveCount(1);
  await page.getByRole("button", { name: "Step-by-Step", exact: true }).click();
  expect(await stepCount()).toBe(1);
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.getByRole("button", { name: "Next step", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  expect(await stepCount()).toBe(2);
  expect(new URL(page.url()).searchParams.get("s")).toBe("9");
  await page.getByRole("button", { name: "Question only", exact: true }).click();
  await expect(root()).toHaveAttribute("data-solution-open", "false");
  await page.waitForTimeout(500);
  expect((await question.boundingBox()).width).toBeCloseTo(initial.width, 0);
  await page.keyboard.press("w");
  expect(await stepCount()).toBe(1);
  await page.getByRole("button", { name: "Next question", exact: true }).click();
  await expect(root()).toHaveAttribute("data-solution-open", "false");
  expect(await stepCount()).toBe(0);
  console.log("ok curated drift, staged working, final answer, backwards, all, dots, keyboard and reset");

  await visit(13);
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  expect(await stepCount()).toBe(1);
  await page.getByText("More ···", { exact: true }).click();
  await page.getByRole("button", { name: "Show answer", exact: true }).click();
  await expect(page.locator("[data-answer]")).toHaveCount(1);
  const before = await page.locator(".solution-question").innerText();
  await page.getByRole("button", { name: "New question", exact: true }).click();
  await expect(root()).toHaveAttribute("data-solution-open", "false");
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await expect(page.locator(".solution-question")).not.toHaveText(before);
  await page.keyboard.press("s");
  expect(await stepCount()).toBe(1);
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${artifacts}/generator.png` });
  console.log("ok generator uses the same unfolding layout and resets on a new question");

  await visit(12);
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  await expect(page.getByText("OUR PICK", { exact: true })).toHaveCount(0);
  await page.getByText("More ···", { exact: true }).click();
  await page.getByRole("button", { name: "Show answer", exact: true }).click();
  await expect(page.locator("[data-answer]")).toHaveCount(1);
  await expect(page.getByText("Correct", { exact: true })).toHaveCount(1);
  console.log("ok diagnostic content and correct-choice feedback remain on the question side");

  await page.goto(`${base}/decks/estimation?edit=1&s=9`);
  await page.locator('div[style*="cursor: move"]').first().dblclick();
  await page.getByRole("dialog", { name: "Skill practice", exact: true }).waitFor();
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  for (const viewport of [{ width: 1366, height: 768 }, { width: 1024, height: 768 }, { width: 390, height: 800 }]) {
    await page.setViewportSize(viewport);
    await page.waitForTimeout(500);
    await expect(page.getByRole("button", { name: "Apply to slide", exact: true })).toBeInViewport();
    const box = await page.getByRole("dialog", { name: "Skill practice", exact: true }).locator(".solution-stepper").boundingBox();
    const w = await page.getByRole("dialog", { name: "Skill practice", exact: true }).getByRole("region", { name: "Worked solution", exact: true }).boundingBox();
    const q = await page.getByRole("dialog", { name: "Skill practice", exact: true }).getByRole("region", { name: "Question", exact: true }).boundingBox();
    if (box.width > 420) expect(w.x + w.width).toBeLessThan(q.x);
    else expect(q.y + q.height).toBeLessThan(w.y);
    const preview = page.getByRole("dialog", { name: "Skill practice", exact: true });
    expect(await preview.locator(".solution-list").evaluate((el) => el.clientHeight)).toBeGreaterThan(50);
    await preview.locator("aside").scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${artifacts}/preview-${viewport.width}.png` });
  }
  await page.emulateMedia({ reducedMotion: "reduce" });
  expect(await page.getByRole("dialog", { name: "Skill practice", exact: true }).locator(".solution-question").evaluate((el) => getComputedStyle(el).transitionDuration)).toBe("0s");
  expect(await page.getByRole("dialog", { name: "Skill practice", exact: true }).locator(".solution-row").first().evaluate((el) => getComputedStyle(el).animationName)).toBe("none");
  expect(errors).toEqual([]);
  console.log(`All solution checks passed. Screenshots: ${artifacts}`);
} finally {
  await browser.close();
}
