// Local browser checks with simulated cameras only. No shared content or real camera is accessed.
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { chromium, expect } = require(process.env.PLAYWRIGHT_PATH ?? "playwright/test");
const artifacts = fs.mkdtempSync("/tmp/whiteboard-smoke-");
const base = process.env.SMOKE_URL ?? "http://127.0.0.1:5173";
const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ["--no-sandbox", "--use-fake-device-for-media-stream=device-count=2", "--use-fake-ui-for-media-stream"] });
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  await page.route("**/api/decks*", (r) => r.fulfill({ status: 503, contentType: "application/json", body: '{}' }));
  await page.addInitScript(() => {
    window.cameraStreams = [];
    window.cameraRequests = 0;
    window.cameraDenied = false;
    window.holdCamera = false;
    const media = navigator.mediaDevices;
    const get = media.getUserMedia.bind(media);
    media.getUserMedia = async (constraints) => {
      window.cameraRequests++;
      if (window.cameraDenied) throw new DOMException("Denied for test", "NotAllowedError");
      if (window.cameraMissing) throw new DOMException("Missing for test", "NotFoundError");
      const stream = await get(constraints); window.cameraStreams.push(stream);
      if (window.holdCamera || (window.holdFinalCamera && typeof constraints.video === "object")) await new Promise((resolve) => { window.releaseCamera = resolve; });
      return stream;
    };
  });
  const allStopped = () => page.evaluate(() => window.cameraStreams.every((s) => s.getTracks().every((t) => t.readyState === "ended")));
  const liveTracks = () => page.evaluate(() => window.cameraStreams.flatMap((s) => s.getTracks()).filter((t) => t.readyState === "live").length);
  const cameraAction = async (name) => {
    const menu = page.locator(".workspace-options");
    if (await menu.getAttribute("open") === null) await page.getByRole("button", { name: "Workspace options", exact: true }).click();
    await page.getByRole("button", { name, exact: true }).click();
  };
  await page.goto(`${base}/decks/estimation?s=13`);
  await page.getByRole("button", { name: "Show working", exact: true }).waitFor();
  expect(await page.evaluate(() => window.cameraRequests)).toBe(0);
  const question = page.getByRole("region", { name: "Question", exact: true });
  const space = page.getByRole("region", { name: "Writing space", exact: true });
  await question.evaluate((el) => { el.dataset.identity = "same-question"; });
  const beforeQ = await question.boundingBox(), beforeSpace = await space.boundingBox();
  expect(beforeQ.x + beforeQ.width).toBeLessThan(beforeSpace.x);
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  await page.waitForTimeout(600);
  const afterQ = await question.boundingBox(), afterSpace = await space.boundingBox();
  const working = await page.getByRole("region", { name: "Worked solution", exact: true }).boundingBox();
  expect(afterQ.height).toBeLessThan(beforeQ.height * 0.4);
  expect(afterQ.y + afterQ.height).toBeLessThan(working.y);
  expect(afterQ.x).toBeCloseTo(beforeQ.x, 0);
  expect(afterSpace).toEqual(beforeSpace);
  await expect(question).toHaveAttribute("data-identity", "same-question");
  await expect(page.locator("[data-explanation]")).toHaveCount(1);
  await page.getByRole("button", { name: "Next step", exact: true }).click();
  await expect(page.locator("[data-explanation]")).toHaveCount(2);
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  await page.locator(".slide-more > summary").click();
  await page.getByRole("button", { name: "Show answer", exact: true }).click();
  await expect(page.locator("[data-answer]")).toHaveCount(1);
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${artifacts}/working.png` });
  await page.getByRole("button", { name: "New question", exact: true }).click();
  await expect(page.locator(".solution-stepper")).toHaveAttribute("data-solution-open", "false");
  await expect(page.locator("[data-answer]")).toHaveCount(0);
  console.log("ok question left, workspace right, upward contraction, canonical steps, final answer and reset");

  await cameraAction("Start visualiser");
  await expect.poll(() => page.locator("video").evaluate((el) => el.videoWidth)).toBeGreaterThan(0);
  expect(await liveTracks()).toBe(1);
  await page.getByRole("button", { name: "Workspace options", exact: true }).click();
  const cameras = page.getByRole("combobox", { name: "Camera", exact: true });
  await cameras.waitFor();
  expect(await cameras.locator("option").count()).toBe(2);
  const ids = await cameras.locator("option").evaluateAll((els) => els.map((el) => el.value));
  const current = await cameras.inputValue();
  await cameras.selectOption(ids.find((id) => id !== current));
  await expect.poll(() => cameras.inputValue()).not.toBe(current);
  await expect.poll(liveTracks).toBe(1);
  await page.getByRole("button", { name: "Show working", exact: true }).click();
  await expect.poll(() => page.locator("video").evaluate((el) => el.videoWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: `${artifacts}/visualiser.png` });
  const requestsBeforeNew = await page.evaluate(() => window.cameraRequests);
  await page.getByRole("button", { name: "New question", exact: true }).click();
  await expect.poll(liveTracks).toBe(1);
  expect(await page.evaluate(() => window.cameraRequests)).toBe(requestsBeforeNew);
  await cameraAction("Stop visualiser");
  await expect.poll(allStopped).toBe(true);
  console.log("ok explicit camera start, video, device switching, solution reveal preserves camera, stop releases tracks");

  await page.evaluate(() => { window.cameraDenied = true; });
  await cameraAction("Start visualiser");
  await expect(page.getByRole("alert")).toContainText("Camera permission was denied");
  await page.evaluate(() => { window.cameraDenied = false; });
  await page.getByRole("button", { name: "Retry camera", exact: true }).click();
  await expect.poll(liveTracks).toBe(1);
  await page.keyboard.press("PageDown");
  await expect.poll(allStopped).toBe(true);
  console.log("ok permission denial, retry and slide-exit cleanup");

  await page.goto(`${base}/decks/estimation?s=13`);
  await page.evaluate(() => { window.holdCamera = true; });
  await cameraAction("Start visualiser");
  await expect.poll(() => page.evaluate(() => typeof window.releaseCamera)).toBe("function");
  await page.keyboard.press("PageDown");
  await page.evaluate(() => { window.holdCamera = false; window.releaseCamera(); });
  await expect.poll(allStopped).toBe(true);
  console.log("ok a camera permission request completing after slide exit also releases its tracks");
  await page.goto(`${base}/decks/estimation?s=13`);
  await page.evaluate(() => { window.holdFinalCamera = true; });
  await cameraAction("Start visualiser");
  await expect.poll(() => page.evaluate(() => typeof window.releaseCamera)).toBe("function");
  await page.keyboard.press("PageDown");
  await page.evaluate(() => { window.holdFinalCamera = false; window.releaseCamera(); });
  await expect.poll(allStopped).toBe(true);
  console.log("ok final camera acquisition completing after exit also releases its tracks");
  await page.goto(`${base}/decks/estimation?s=13`);
  await page.evaluate(() => { window.cameraMissing = true; });
  await cameraAction("Start visualiser");
  await expect(page.getByRole("alert")).toContainText("No camera was found");
  await cameraAction("Stop visualiser");
  await expect(page.getByRole("region", { name: "Writing space", exact: true })).toHaveAttribute("data-camera-active", "false");

  await page.goto(`${base}/decks/estimation?edit=1&s=13`);
  await page.locator('div[style*="cursor: move"]').first().dblclick();
  const dialog = page.getByRole("dialog", { name: "Configure generator", exact: true });
  await expect(dialog.getByRole("button", { name: /Workspace right/ })).toHaveAttribute("aria-pressed", "true");
  expect(await page.evaluate(() => window.cameraRequests)).toBe(0);
  await dialog.getByRole("checkbox", { name: "Offer camera visualiser when presenting", exact: true }).uncheck();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.locator('div[style*="cursor: move"]').first().dblclick();
  await expect(dialog.getByRole("checkbox", { name: "Offer camera visualiser when presenting", exact: true })).toBeChecked();
  await dialog.getByRole("checkbox", { name: "Offer camera visualiser when presenting", exact: true }).uncheck();
  await dialog.getByRole("button", { name: "Apply to slide", exact: true }).click();
  await page.getByRole("button", { name: "Present", exact: true }).click();
  await expect(page.getByRole("region", { name: "Writing space", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Start visualiser", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Workspace options", exact: true })).toHaveCount(0);
  for (const viewport of [{ width: 1366, height: 768 }, { width: 1024, height: 768 }, { width: 390, height: 800 }]) {
    await page.setViewportSize(viewport);
    await page.waitForTimeout(250);
    const initial = await space.boundingBox();
    await page.keyboard.press("s"); await page.waitForTimeout(500);
    const q = await question.boundingBox(), w = await page.getByRole("region", { name: "Worked solution", exact: true }).boundingBox();
    expect(q.y + q.height).toBeLessThan(w.y); expect(await space.boundingBox()).toEqual(initial);
    await page.screenshot({ path: `${artifacts}/layout-${viewport.width}.png` });
    await page.keyboard.press("a"); await page.keyboard.press("a");
  }
  await page.emulateMedia({ reducedMotion: "reduce" });
  expect(await question.evaluate((el) => getComputedStyle(el).transitionDuration)).toBe("0s");
  expect(errors).toEqual([]);
  console.log(`All Whiteboard checks passed. Screenshots: ${artifacts}`);
} finally { await browser.close(); }
